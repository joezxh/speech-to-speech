"""Turn a patch into the bytes of `config/<profile>.yaml` and `<profile>.env`.

The renderer never invents structure. It loads the file that is already there,
applies the patch at the paths `layout` names, prunes what a delete emptied, and
dumps. That keeps a publish diff to the parameters actually touched instead of
rewriting the whole file from a template and burying the change.

Byte-stability matters: the same draft must render to the same bytes, or an
audit diff shows noise and a rolled-back version cannot be compared to the one
it replaced.
"""

from __future__ import annotations

import copy
import logging
import re
from pathlib import Path
from typing import Any

import yaml
from param_platform import layout

logger = logging.getLogger("s2s.params")

# `{env: NAME}` is a mapping, not a string. Dumped in block style it stays valid
# but reads like a nested object and invites someone to write `"{env: NAME}"`
# with quotes, which `resolve_config` would then treat as a literal credential
# (spec §12 R9). Keep it on one line.
_ENV_KEY = "env"

_ENV_LINE = re.compile(r"^(?P<key>[A-Za-z_][A-Za-z0-9_]*)=(?P<value>.*)$")


class _Dumper(yaml.SafeDumper):
    pass


def _represent_dict(dumper: yaml.SafeDumper, data: dict[str, Any]) -> yaml.Node:
    flow = len(data) == 1 and _ENV_KEY in data
    return dumper.represent_mapping("tag:yaml.org,2002:map", data.items(), flow_style=flow)


_Dumper.add_representer(dict, _represent_dict)


def load_base(path: Path) -> dict[str, Any]:
    """The file as it is now, or an empty scaffold when it does not exist yet.

    Deliberately `yaml.safe_load` rather than `load_config`: rendering must
    round-trip everything in the file, including keys the runtime would reject,
    so that a broken file stays visible instead of being silently normalised.
    """
    if not path.is_file():
        return {"schema_version": 1, "blocks": {}, "pipelines": {}, "runtime": {}}

    document = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(document, dict):
        raise ValueError(f"{path} does not hold a mapping at the top level")
    return document


def split_patches(
    patches: dict[str, Any], entries: dict[str, Any]
) -> tuple[dict[str, Any], dict[str, Any]]:
    """Split `<stage>.<name>` patches into YAML values and `.env` values.

    The 18 `stage: env` parameters have no YAML location by construction — they
    are the values `{env: NAME}` resolves against. Routing them to the wrong
    file would either be rejected by `apply` or, worse, written into the YAML as
    a literal.
    """
    yaml_patches: dict[str, Any] = {}
    env_patches: dict[str, Any] = {}
    for key, value in patches.items():
        entry = entries.get(key)
        if entry is not None and entry.stage == "env":
            env_patches[entry.name] = value
        else:
            yaml_patches[key] = value
    return yaml_patches, env_patches


def render_yaml(
    base: dict[str, Any],
    profile: str,
    patches: dict[str, Any],
    entries: dict[str, Any],
) -> tuple[str, list[str], list[dict[str, str]]]:
    """`(text, applied, refused)`. A refused key never reaches the text.

    The caller must treat a nonempty `refused` as a failed render: silently
    dropping half a patch and publishing the rest is how a deployed config ends
    up different from the one that was reviewed.
    """
    document = copy.deepcopy(base)
    applied, refused = layout.apply(document, profile, patches, entries)
    return dump_yaml(document), applied, refused


def dump_yaml(document: dict[str, Any]) -> str:
    header = (
        "# Generated by the deployment parameter platform.\n"
        "# Edit through the console: a manual change is overwritten on the next\n"
        "# publish and will not appear in the version history.\n"
    )
    body = yaml.dump(
        document,
        Dumper=_Dumper,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        # Long prompts and URLs stay on one line. YAML folds them faithfully
        # either way, but an unfolded value diffs as one line instead of five.
        width=1000,
    )
    return header + body


# ── .env ─────────────────────────────────────────────────────────────────────


def render_env(existing: str, patches: dict[str, Any]) -> tuple[str, list[str]]:
    """Rewrite `.env` keeping comments, order and unknown keys.

    A `null` patch removes the line. Removing a key that a `{env: NAME}`
    reference still needs is caught by the validator, not here: the renderer's
    job is to produce the file the operator asked for, and a silent keep would
    make the console's delete button do nothing.
    """
    applied: list[str] = []
    remaining = dict(patches)
    output: list[str] = []

    for line in existing.splitlines():
        match = _ENV_LINE.match(line)
        if match is None:
            output.append(line)
            continue
        key = match.group("key")
        if key not in remaining:
            output.append(line)
            continue
        value = remaining.pop(key)
        applied.append(key)
        if value is not None:
            output.append(f"{key}={_env_value(value)}")

    for key, value in remaining.items():
        if value is None:
            continue
        applied.append(key)
        output.append(f"{key}={_env_value(value)}")

    text = "\n".join(output).rstrip("\n") + "\n"
    return text, applied


def _env_value(value: Any) -> str:
    if isinstance(value, bool):
        return "1" if value else "0"
    return str(value)


def parse_env(text: str) -> dict[str, str]:
    """The key/value pairs of an `.env`, for redaction and diffing."""
    values: dict[str, str] = {}
    for line in text.splitlines():
        match = _ENV_LINE.match(line)
        if match:
            values[match.group("key")] = match.group("value")
    return values


# ── diff ─────────────────────────────────────────────────────────────────────


def diff_values(before: dict[str, Any], after: dict[str, Any]) -> list[dict[str, Any]]:
    """Per-key changes, which is what the audit log records (spec §10.1).

    Values are compared after `repr` so that `700` and `"700"` show up as a
    change: they are different to the validator, and hiding that would make a
    rejected publish look unexplained.
    """
    changes: list[dict[str, Any]] = []
    for key in sorted(set(before) | set(after)):
        old = before.get(key, layout.MISSING)
        new = after.get(key, layout.MISSING)
        if old is layout.MISSING and new is layout.MISSING:
            continue
        if repr(old) == repr(new):
            continue
        changes.append(
            {
                "key": key,
                "before": None if old is layout.MISSING else old,
                "after": None if new is layout.MISSING else new,
            }
        )
    return changes
