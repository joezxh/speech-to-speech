"""Render the console schema as plain SQL — one file per dialect.

`alembic upgrade head --sql` renders the *same* migration code that runs at
deploy time, so `alembic/sql/init-*.sql` cannot drift from `alembic/versions/`
without the regeneration showing up in the diff. The files exist for
provisioning a database by hand (`psql -f …`, `sqlite3 db < …`); the app itself
still upgrades with `alembic upgrade head`.

Each dialect needs its own run because `alembic/env.py` reads `DATABASE_URL`
from `app.config` at import time, and that module caches the settings — hence a
subprocess per dialect instead of a second in-process run.

Usage, from `console/backend`:

    python scripts/dump_schema_sql.py
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
OUT_DIR = BACKEND / "alembic" / "sql"

# Offline mode never opens a connection, so these are only dialect selectors.
# They are deliberately unreachable-looking: running the files by hand is fine,
# pointing the app at them is not.
DIALECTS = {
    "sqlite": "sqlite:////nonexistent/console.sqlite3",
    "postgresql": "postgresql+psycopg2://s2s:s2s@127.0.0.1:5432/s2s",
}

HEADER = """\
-- Console schema for {dialect}, generated by `scripts/dump_schema_sql.py` from \
`alembic upgrade head --sql`.
-- Do not edit: change `alembic/versions/` and re-run the script.
--
-- This file creates the tables *and* stamps `alembic_version`, so a database
-- initialised from it is already at head and `alembic upgrade head` is a no-op.
-- It is idempotent only in the sense that re-running it fails on the existing
-- tables — provision an empty database with it.
{note}"""

NOTES = {
    # Both floors come from the generated statements, not from a preference:
    # the version stamp is an INSERT ... RETURNING, and the tables use SERIAL.
    "sqlite": "-- Needs SQLite 3.35+ (the version stamp is an INSERT ... RETURNING).\n",
    "postgresql": "-- Needs PostgreSQL 12+ (SERIAL keys, JSON columns, TIMESTAMPTZ).\n",
}


def render(dialect: str, url: str) -> str:
    env = {
        **os.environ,
        "DATABASE_URL": url,
        # `app.config` refuses to import without it, and alembic/env.py imports
        # it for the URL. The value is never used: offline mode signs nothing.
        "JWT_SECRET_KEY": "schema-dump-placeholder-at-least-32-bytes",
        "PYTHONPATH": ".",
    }
    completed = subprocess.run(
        [sys.executable, "-m", "alembic", "upgrade", "head", "--sql"],
        cwd=BACKEND,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise SystemExit(f"alembic failed for {dialect}:\n{completed.stderr}")
    body = completed.stdout.lstrip("\n")
    if "CREATE TABLE" not in body:
        raise SystemExit(f"alembic produced no DDL for {dialect}:\n{completed.stderr}")
    # Alembic ends each column line with ", " — keep the file diff-clean.
    body = "\n".join(line.rstrip() for line in body.splitlines()) + "\n"
    return HEADER.format(dialect=dialect, note=NOTES[dialect]) + "\n" + body


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for dialect, url in DIALECTS.items():
        target = OUT_DIR / f"init-{dialect}.sql"
        text = render(dialect, url).replace("\r\n", "\n")
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target.relative_to(BACKEND)} ({target.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
